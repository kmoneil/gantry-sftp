# --- driving it against a real server -------------------------------------------------------


def test_a_blocking_round_trip_moves_the_bytes(tmp_path: Path):
    """The whole facade in one test: two context managers, a put, a get, and no event loop."""
    needs_real_server()
    source = tmp_path / "report.csv"
    source.write_bytes(b"id,total\n1,42\n")

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        assert isinstance(transport, SyncTransport)
        assert isinstance(sftp, SyncSession)
        result = sftp.put(source, str(tmp_path / "uploaded.csv").encode())
        fetched = sftp.get(str(tmp_path / "uploaded.csv").encode(), tmp_path / "back.csv")

    assert result.transferred == len(source.read_bytes())
    # The blocking surface hands back the same result type the async one does -- the portal
    # carries an object across the thread boundary exactly as it carries an int.
    assert isinstance(fetched, DownloadResult)
    assert fetched.transferred == len(source.read_bytes())
    assert (tmp_path / "back.csv").read_bytes() == source.read_bytes()


def test_the_session_runs_on_a_thread_that_is_not_the_callers(tmp_path: Path):
    """The mechanism, asserted rather than assumed.

    If this ever ran the loop on the calling thread, every blocking call would be re-entrant
    and the failure would look like an unrelated deadlock much later.
    """
    needs_real_server()
    caller = threading.get_ident()
    seen: list[int] = []

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        _ = transport.portal.call(lambda: _record(seen))
        assert sftp.server_version == 3

    assert seen, "the portal never ran anything"
    assert seen[0] != caller


async def _record(seen: list[int]) -> None:
    seen.append(threading.get_ident())


def test_an_error_arrives_as_itself_and_flat(tmp_path: Path):
    """What the reader's shielding and the group flattening buy, across the thread boundary.

    A mechanism that re-wrapped exceptions would have undone all of it silently: an anyio task
    group wraps even a single failure, and a caller who wrote `except NoSuchFileError` around
    a blocking call would stop matching.
    """
    needs_real_server()
    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
        pytest.raises(NoSuchFileError) as error,
    ):
        sftp.stat(str(tmp_path / "definitely-not-here").encode())

    assert not isinstance(error.value, BaseExceptionGroup)
    assert error.value.code == 2


def test_breaking_out_of_a_scandir_closes_the_handle_on_the_server(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """The question the D-8 probe deliberately left open, answered against a real server.

    The probe proved the `__aexit__` reached the portal's thread and returned. That is not the
    same claim as the handle being gone -- and "no complaint appeared" is not evidence, it is
    the absence of evidence. `close()` of an unknown handle answers `NO_SUCH_FILE` rather than
    the v3 catch-all `FAILURE`, so asking the server directly is a real probe.

    The handle is captured by spying on `opendir`, which is public API, rather than by reaching
    into the scan -- `DirectoryScan` clears its handle on the way out, so by the time the block
    has ended there is nothing left there to read.
    """
    needs_real_server()
    for index in range(6):
        (tmp_path / f"part-{index}.bin").write_bytes(b"x" * (index + 1))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        handles = _spying_on_opendir(monkeypatch)
        with sftp.scandir(str(tmp_path).encode()) as entries:
            for _ in entries:
                break  # the case the card calls the real failure mode

        assert len(handles) == 1, "the scan did not open exactly one directory"
        with pytest.raises(NoSuchFileError) as error:
            sftp.close(handles[0])
