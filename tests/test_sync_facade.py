def test_a_method_returns_what_the_async_one_returns(name: str):
    """Awaiting is the portal's job, so the return type is unchanged except where it cannot be."""
    assert name in SYNC_MEMBERS, f"{name} has no blocking form at all"
    theirs = inspect.signature(ASYNC_MEMBERS[name]).return_annotation
    ours = inspect.signature(SYNC_MEMBERS[name]).return_annotation
    expected_from, expected_to = RETURN_TRANSLATIONS.get(name, (theirs, theirs))
    assert theirs == expected_from, f"{name}'s async return type changed; the translation is stale"
    assert ours == expected_to


