# --- what the facade is derived from -------------------------------------------------------


def public_members(cls: type) -> dict[str, Any]:
    """Everything a caller can reach on a class, without triggering a descriptor.

    `getattr_static` rather than `getattr`, because a `property` read on the class would give
    back the property object anyway but a `getattr` on an instance would run it.
    """
    return {
        name: inspect.getattr_static(cls, name) for name in dir(cls) if not name.startswith("_")
    }


ASYNC_MEMBERS = public_members(Session)
SYNC_MEMBERS = public_members(SyncSession)

RETURN_TRANSLATIONS = {
    "walk": ("AsyncGenerator[WalkEntry]", "Iterator[WalkEntry]"),
    "glob": ("AsyncGenerator[GlobMatch]", "Iterator[GlobMatch]"),
    "scandir": ("DirectoryScan", "SyncDirectoryScan"),
}
"""The three members whose return type legitimately changes, and what it changes to.

Every other method returns exactly what the async one returns -- awaiting is what the portal
does, so `get` is still `-> int`. These three are the shapes that could not survive the thread
boundary unchanged: two async generators, which become ordinary Python iterators, and the
directory scan, which becomes the blocking context manager of the same shape.

Named rather than skipped, and checked in both directions below, so the list cannot outlive
its reason or quietly grow a fourth entry nobody argued for.
"""


def test_the_derivation_is_not_vacuous():
    # Guards the guards: every parity test below is a loop over these, and an empty dict
    # would make all of them pass while proving nothing.
    assert len(ASYNC_MEMBERS) > 40
    assert sum(inspect.iscoroutinefunction(m) for m in ASYNC_MEMBERS.values()) > 25


def test_every_session_method_has_a_blocking_form():
    """The headline. A method added to `Session` and forgotten here shows up as a name."""
    missing = sorted(set(ASYNC_MEMBERS) - set(SYNC_MEMBERS))
    assert missing == [], f"Session methods with no blocking form: {missing}"


def test_the_facade_invents_nothing_of_its_own():
    """The other direction, which is what stops the facade becoming a second API.

    A blocking-only convenience method would have nothing to be derived from and nothing to
    keep it honest -- it is exactly the drift the generated twin was meant to prevent.
    """
    extra = sorted(set(SYNC_MEMBERS) - set(ASYNC_MEMBERS))
    assert extra == [], f"SyncSession has public members Session does not: {extra}"


@pytest.mark.parametrize(
    "name", sorted(n for n, m in ASYNC_MEMBERS.items() if isinstance(m, property))
)
def test_a_property_stays_a_property(name: str):
    """`sftp.depth` must not become `sftp.depth()` on the way across the thread.

    Properties read state that is already in memory, so none of them needs the portal -- but
    that is a reason for them to be cheap, not a reason for them to change shape.
    """
    assert isinstance(SYNC_MEMBERS[name], property), f"{name} is a property on Session but not here"


@pytest.mark.parametrize(
    "name", sorted(n for n, m in ASYNC_MEMBERS.items() if not isinstance(m, property))
)
def test_a_method_keeps_its_signature(name: str):
    """Every parameter, in order, with its annotation and its default.

    `inspect.Parameter` compares name, kind, annotation and default, and `from __future__
    import annotations` makes the annotations strings on both sides -- so this also catches a
    facade that spells a type differently from the method it is forwarding to, which is how a
    reader ends up with two different answers to the same question.
    """
    assert name in SYNC_MEMBERS, f"{name} has no blocking form at all"
    theirs = inspect.signature(ASYNC_MEMBERS[name])
    ours = inspect.signature(SYNC_MEMBERS[name])
    assert list(ours.parameters.values()) == list(theirs.parameters.values())


@pytest.mark.parametrize(
    "name", sorted(n for n, m in ASYNC_MEMBERS.items() if not isinstance(m, property))
)
def test_a_method_returns_what_the_async_one_returns(name: str):
    """Awaiting is the portal's job, so the return type is unchanged except where it cannot be."""
    assert name in SYNC_MEMBERS, f"{name} has no blocking form at all"
    theirs = inspect.signature(ASYNC_MEMBERS[name]).return_annotation
    ours = inspect.signature(SYNC_MEMBERS[name]).return_annotation
    expected_from, expected_to = RETURN_TRANSLATIONS.get(name, (theirs, theirs))
    assert theirs == expected_from, f"{name}'s async return type changed; the translation is stale"
    assert ours == expected_to


def test_the_translation_table_has_no_stale_entries():
    """A translation naming a method that no longer exists is a permission nobody needs."""
    stale = sorted(set(RETURN_TRANSLATIONS) - set(ASYNC_MEMBERS))
    assert stale == [], f"translated but no longer a Session method: {stale}"


def test_only_the_streaming_shapes_are_translated():
    """The entries are exactly the members that cannot cross the boundary unchanged.

    Derived rather than restated: an async generator or a hand-written async context manager
    has to become something else, and nothing else does.
    """
    must_translate = {
        name
        for name, member in ASYNC_MEMBERS.items()
        if not isinstance(member, property)
        and (
            inspect.isasyncgenfunction(member)
            or inspect.signature(member).return_annotation == "DirectoryScan"
        )
    }
    assert set(RETURN_TRANSLATIONS) == must_translate


