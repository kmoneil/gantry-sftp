"""The blocking surface, and the parity check that replaces a code generator.

D-8 decided the sync API is a portal facade rather than a twin generated by `unasync`, and
the reason the decision was affordable is written into this file. A generator guarantees that
the two surfaces cannot drift; a facade has to *prove* it, and the proof is cheap because
drift is possible in arity and not in semantics -- there is one implementation of a `get`,
and `SyncSession.get` is that method with a portal in front of it.

So the parity tests below are **derived from `Session` rather than listed**. A method added to
the async API and forgotten here fails `test_every_session_method_has_a_blocking_form`; an
argument renamed on one side fails the signature comparison; a return type changed fails that
too. A hand-written list of names would be a second enumeration of the API, which is the
failure D-52 is in this repository to memorialise.

The behavioural half runs against a real `sftp-server` on a pipe, because that is where the
questions the probe left open actually live -- above all: after a sync caller `break`s out of
a `scandir`, the `__aexit__` demonstrably ran, but **is the server-side handle gone?** A
`close()` of an unknown handle answers `NO_SUCH_FILE` rather than the v3 catch-all, which
makes that a usable leak probe rather than an inference from the absence of a complaint.
"""

