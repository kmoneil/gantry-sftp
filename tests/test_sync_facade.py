def test_several_threads_share_one_session_over_one_connection(tmp_path: Path):
    """The blocking spelling of this library's headline feature, which is `except` for threads.

    "Many transfers, one connection" is a task group asynchronously. A blocking caller has no
    task group, so the question is whether a `SyncSession` survives being called from several
    threads at once -- and it does, for a reason worth stating: `portal.call` posts to the loop
    from whatever thread it is on, so the fan-out lands on the one reader that already routes
    replies by request id. Without this a blocking user has no way to overlap transfers at all.
    """
    needs_real_server()
    for index in range(8):
        (tmp_path / f"src-{index}.bin").write_bytes(b"x" * (10_000 * (index + 1)))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):

        def fetch(index: int) -> int:
            return sftp.get(
                str(tmp_path / f"src-{index}.bin").encode(), tmp_path / f"dst-{index}.bin"
            ).transferred

        with ThreadPoolExecutor(max_workers=8) as pool:
            transferred = list(pool.map(fetch, range(8)))

    assert transferred == [10_000 * (index + 1) for index in range(8)]
    for index in range(8):
        assert (tmp_path / f"dst-{index}.bin").stat().st_size == 10_000 * (index + 1)


