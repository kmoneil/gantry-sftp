def test_one_portal_can_carry_several_sessions(tmp_path: Path):
    """The reason `BoundPortal` exists: a thread and a loop per connection is a real cost.

    Both sessions are live at once and both work, which is what a fan-out job needs and what
    portal-per-connection charges a thread apiece for.
    """
    needs_real_server()
    (tmp_path / "one.bin").write_bytes(b"1")
    (tmp_path / "two.bin").write_bytes(b"22")

    with start_blocking_portal() as portal:
        gantry = BoundPortal(portal)
        assert gantry.portal is portal
        with (
            gantry.open_local_server_transport(cwd=tmp_path) as first_transport,
            gantry.open_session(first_transport) as first,
            gantry.open_local_server_transport(cwd=tmp_path) as second_transport,
            gantry.open_session(second_transport) as second,
        ):
            assert first.stat(b"one.bin").size == 1
            assert second.stat(b"two.bin").size == 2
            # Still one loop, so still one thread doing the work for both.
            assert first_transport.portal is second_transport.portal


def test_a_caller_can_run_the_facade_on_trio(tmp_path: Path):
    """The other reason to own the portal, and the one that would have been a `backend=` argument.

    This library is anyio-shaped so that trio costs nothing, and a blocking surface pinned to
    asyncio would spend that for the caller. Owning the portal is the whole of the answer.
    """
    needs_real_server()
    (tmp_path / "one.bin").write_bytes(b"1")

    with start_blocking_portal(backend="trio") as portal:
        gantry = BoundPortal(portal)
        with (
            gantry.open_local_server_transport(cwd=tmp_path) as transport,
            gantry.open_session(transport) as sftp,
        ):
            assert sftp.stat(b"one.bin").size == 1
            assert sorted(entry.name for entry in sftp.listdir(b".")) == ["one.bin"]


def test_the_portal_a_caller_owns_outlives_the_session(tmp_path: Path):
    """Nothing in the facade starts or stops a portal it was handed."""
    needs_real_server()
    with start_blocking_portal() as portal:
        gantry = BoundPortal(portal)
        with (
            gantry.open_local_server_transport(cwd=tmp_path) as transport,
            gantry.open_session(transport) as sftp,
        ):
            assert sftp.server_version == 3
        # The session is spent and the portal is not: a second one opens on the same loop.
        with (
            gantry.open_local_server_transport(cwd=tmp_path) as again_transport,
            gantry.open_session(again_transport) as again,
        ):
            assert again.server_version == 3


def test_the_bound_portal_repr_names_the_portal():
    """Which portal, not just that there is one -- with several in play that is the question."""
    with start_blocking_portal() as portal:
        rendered = repr(BoundPortal(portal))
        assert rendered.startswith("<BoundPortal ")
        assert repr(portal) in rendered


