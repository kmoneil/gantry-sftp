def test_the_scan_wraps_the_async_one_rather_than_reimplementing_it(tmp_path: Path):
    """Stated as an identity, because the alternative is a second directory reader.

    `SyncDirectoryScan` holds a `DirectoryScan`; the batching, the dot filtering and the
    latched EOF are that object's and are tested where it lives.
    """
    needs_real_server()
    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        scan = sftp.scandir(b".")
        assert isinstance(scan._scan, DirectoryScan)  # noqa: SLF001


def test_the_transport_hands_back_the_async_object_it_carries(tmp_path: Path):
    """`SyncTransport.transport` is the escape hatch, and it is the real transport."""
    needs_real_server()
    with open_local_server_transport(cwd=tmp_path) as transport:
        assert hasattr(transport.transport, "send")
        assert hasattr(transport.transport, "receive")
