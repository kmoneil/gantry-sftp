def test_the_session_refuses_calls_after_its_block_has_ended(tmp_path: Path):
    """Naming the mistake rather than the mechanism.

    Without this the same call surfaces as anyio's "This portal is not running", which tells a
    reader about a thread they never asked for instead of about the `with` block they left.
    """
    needs_real_server()
    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        assert sftp.server_version == 3

    with pytest.raises(StateError) as error:
        sftp.listdir(str(tmp_path).encode())
    assert error.value.args[0] == "this session is closed; its `with` block has ended"

    # `scandir` is not a blocking call, so it would otherwise sail past the check and fail
    # later, inside a `with`, as anyio's complaint about a portal instead.
    with pytest.raises(StateError) as deferred:
        sftp.scandir(str(tmp_path).encode())
    assert deferred.value.args[0] == "this session is closed; its `with` block has ended"


