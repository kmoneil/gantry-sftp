# --- driving it against a real server -------------------------------------------------------


def test_a_blocking_round_trip_moves_the_bytes(tmp_path: Path):
    """The whole facade in one test: two context managers, a put, a get, and no event loop."""
    needs_real_server()
    source = tmp_path / "report.csv"
    source.write_bytes(b"id,total\n1,42\n")

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        assert isinstance(transport, SyncTransport)
        assert isinstance(sftp, SyncSession)
        result = sftp.put(source, str(tmp_path / "uploaded.csv").encode())
        transferred = sftp.get(str(tmp_path / "uploaded.csv").encode(), tmp_path / "back.csv")

    assert result.transferred == len(source.read_bytes())
    assert transferred == len(source.read_bytes())
    assert (tmp_path / "back.csv").read_bytes() == source.read_bytes()


def test_the_session_runs_on_a_thread_that_is_not_the_callers(tmp_path: Path):
    """The mechanism, asserted rather than assumed.

    If this ever ran the loop on the calling thread, every blocking call would be re-entrant
    and the failure would look like an unrelated deadlock much later.
    """
    needs_real_server()
    caller = threading.get_ident()
    seen: list[int] = []

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        _ = transport.portal.call(lambda: _record(seen))
        assert sftp.server_version == 3

    assert seen, "the portal never ran anything"
    assert seen[0] != caller


async def _record(seen: list[int]) -> None:
    seen.append(threading.get_ident())


def test_an_error_arrives_as_itself_and_flat(tmp_path: Path):
    """What the reader's shielding and the group flattening buy, across the thread boundary.

    A mechanism that re-wrapped exceptions would have undone all of it silently: an anyio task
    group wraps even a single failure, and a caller who wrote `except NoSuchFileError` around
    a blocking call would stop matching.
    """
    needs_real_server()
    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
        pytest.raises(NoSuchFileError) as error,
    ):
        sftp.stat(str(tmp_path / "definitely-not-here").encode())

    assert not isinstance(error.value, BaseExceptionGroup)
    assert error.value.code == 2


def test_breaking_out_of_a_scandir_closes_the_handle_on_the_server(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """The question the D-8 probe deliberately left open, answered against a real server.

    The probe proved the `__aexit__` reached the portal's thread and returned. That is not the
    same claim as the handle being gone -- and "no complaint appeared" is not evidence, it is
    the absence of evidence. `close()` of an unknown handle answers `NO_SUCH_FILE` rather than
    the v3 catch-all `FAILURE`, so asking the server directly is a real probe.

    The handle is captured by spying on `opendir`, which is public API, rather than by reaching
    into the scan -- `DirectoryScan` clears its handle on the way out, so by the time the block
    has ended there is nothing left there to read.
    """
    needs_real_server()
    for index in range(6):
        (tmp_path / f"part-{index}.bin").write_bytes(b"x" * (index + 1))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        handles = _spying_on_opendir(monkeypatch)
        with sftp.scandir(str(tmp_path).encode()) as entries:
            for _ in entries:
                break  # the case the card calls the real failure mode

        assert len(handles) == 1, "the scan did not open exactly one directory"
        with pytest.raises(NoSuchFileError) as error:
            sftp.close(handles[0])
        assert error.value.code == 2


def test_breaking_out_of_a_walk_closes_the_handle_on_the_server(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """The same question for the async-generator shape, which fails a different way.

    `walk` chains several async generators, and only closing the outermost one closes those.
    A sync `for` that breaks drops the generator, CPython closes it, and the `finally` inside
    has to reach the portal's thread -- three places this can be swallowed, so it is probed
    rather than reasoned about.
    """
    needs_real_server()
    (tmp_path / "nested").mkdir()
    (tmp_path / "nested" / "leaf.bin").write_bytes(b"x")

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        handles = _spying_on_opendir(monkeypatch)
        for _ in sftp.walk(str(tmp_path).encode()):
            break

        assert handles, "the walk did not open a directory"
        for handle in handles:
            with pytest.raises(NoSuchFileError):
                sftp.close(handle)


def _spying_on_opendir(monkeypatch: pytest.MonkeyPatch) -> list[bytes]:
    """Record every directory handle the server issues, whoever asked for it.

    On `Session` rather than on the facade, because that is who `DirectoryScan` and `walk`
    call -- a spy on `SyncSession.opendir` records only the handles a *caller* opened by hand,
    which is none of the ones under test here. The handles are the server's own, so what this
    proves later is about the server's state and not about a fake's bookkeeping.
    """
    handles: list[bytes] = []
    real = Session.opendir

    async def spy(session: Session, path: bytes | str) -> bytes:
        handle = await real(session, path)
        handles.append(handle)
        return handle

    monkeypatch.setattr(Session, "opendir", spy)
    return handles


def test_a_scandir_that_was_never_entered_refuses_to_iterate(tmp_path: Path):
    """The state check comes from the object underneath rather than a second copy of it.

    Iterating a scan outside its `with` would leak the handle it holds, and the blocking form
    must refuse for the same reason and with the same message as the async one.
    """
    needs_real_server()
    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        scan = sftp.scandir(str(tmp_path).encode())
        assert isinstance(scan, SyncDirectoryScan)
        with pytest.raises(StateError) as error:
            iter(scan)
        assert error.value.args[0] == "scandir() must be entered with `async with` before iterating"


def test_a_scandir_streams_every_entry(tmp_path: Path):
    needs_real_server()
    for index in range(5):
        (tmp_path / f"part-{index}.bin").write_bytes(b"x" * (index + 1))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
        sftp.scandir(str(tmp_path).encode()) as entries,
    ):
        names = sorted(entry.name for entry in entries)

    assert names == [f"part-{index}.bin" for index in range(5)]


def test_walk_and_glob_come_back_as_ordinary_iterators(tmp_path: Path):
    needs_real_server()
    (tmp_path / "nested").mkdir()
    (tmp_path / "nested" / "a.csv").write_bytes(b"a")
    (tmp_path / "nested" / "b.csv").write_bytes(b"b")
    (tmp_path / "nested" / "c.txt").write_bytes(b"c")

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        walked = list(sftp.walk(str(tmp_path).encode()))
        matched = sorted(match.path for match in sftp.glob(str(tmp_path / "*" / "*.csv").encode()))

    assert sorted(entry.path for entry in walked) == sorted(
        [str(tmp_path).encode(), str(tmp_path / "nested").encode()]
    )
    assert matched == [
        str(tmp_path / "nested" / "a.csv").encode(),
        str(tmp_path / "nested" / "b.csv").encode(),
    ]


def test_several_threads_share_one_session_over_one_connection(tmp_path: Path):
    """The blocking spelling of this library's headline feature, which is `except` for threads.

    "Many transfers, one connection" is a task group asynchronously. A blocking caller has no
    task group, so the question is whether a `SyncSession` survives being called from several
    threads at once -- and it does, for a reason worth stating: `portal.call` posts to the loop
    from whatever thread it is on, so the fan-out lands on the one reader that already routes
    replies by request id. Without this a blocking user has no way to overlap transfers at all.
    """
    needs_real_server()
    for index in range(8):
        (tmp_path / f"src-{index}.bin").write_bytes(b"x" * (10_000 * (index + 1)))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):

        def fetch(index: int) -> int:
            return sftp.get(
                str(tmp_path / f"src-{index}.bin").encode(), tmp_path / f"dst-{index}.bin"
            )

        with ThreadPoolExecutor(max_workers=8) as pool:
            transferred = list(pool.map(fetch, range(8)))

    assert transferred == [10_000 * (index + 1) for index in range(8)]
    for index in range(8):
        assert (tmp_path / f"dst-{index}.bin").stat().st_size == 10_000 * (index + 1)


def test_a_progress_callback_still_reports(tmp_path: Path):
    """Callbacks cross the boundary in the other direction: our thread calls the caller's code."""
    needs_real_server()
    source = tmp_path / "big.bin"
    source.write_bytes(b"x" * 200_000)
    seen: list[tuple[int, int | None]] = []

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        sftp.put(
            source,
            str(tmp_path / "up.bin").encode(),
            progress=lambda done, total: seen.append((done, total)),
        )

    assert seen, "the progress callback was never called"
    assert seen[-1] == (200_000, 200_000)


def test_a_callback_that_calls_back_in_fails_loudly_rather_than_deadlocking(tmp_path: Path):
    """The hazard the portal shape creates, probed rather than asserted to be impossible.

    A `progress` callback runs on the portal's thread, and that is the one thread that cannot
    wait on the portal. anyio refuses it; the failure mode worth ruling out is the other one,
    where the call waits for a loop that is waiting for it.
    """
    needs_real_server()
    source = tmp_path / "big.bin"
    source.write_bytes(b"x" * 200_000)
    refusals: list[str] = []

    def reentrant(done: int, total: int | None) -> None:
        try:
            sftp.stat(b".")
        except RuntimeError as error:
            refusals.append(str(error))

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        sftp.put(source, str(tmp_path / "up.bin").encode(), progress=reentrant)

    assert refusals
    assert refusals[0] == "This method cannot be called from the event loop thread"


