def test_breaking_out_of_a_walk_closes_the_handle_on_the_server(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """The same question for the async-generator shape, which fails a different way.

    `walk` chains several async generators, and only closing the outermost one closes those.
    A sync `for` that breaks drops the generator, CPython closes it, and the `finally` inside
    has to reach the portal's thread -- three places this can be swallowed, so it is probed
    rather than reasoned about.
    """
    needs_real_server()
    (tmp_path / "nested").mkdir()
    (tmp_path / "nested" / "leaf.bin").write_bytes(b"x")

    with (
        open_local_server_transport(cwd=tmp_path) as transport,
        open_session(transport) as sftp,
    ):
        handles = _spying_on_opendir(monkeypatch)
        for _ in sftp.walk(str(tmp_path).encode()):
            break

        assert handles, "the walk did not open a directory"
        for handle in handles:
            with pytest.raises(NoSuchFileError):
                sftp.close(handle)


def _spying_on_opendir(monkeypatch: pytest.MonkeyPatch) -> list[bytes]:
    """Record every directory handle the server issues, whoever asked for it.

    On `Session` rather than on the facade, because that is who `DirectoryScan` and `walk`
    call -- a spy on `SyncSession.opendir` records only the handles a *caller* opened by hand,
    which is none of the ones under test here. The handles are the server's own, so what this
    proves later is about the server's state and not about a fake's bookkeeping.
    """
    handles: list[bytes] = []
    real = Session.opendir

    async def spy(session: Session, path: bytes | str) -> bytes:
        handle = await real(session, path)
        handles.append(handle)
        return handle

    monkeypatch.setattr(Session, "opendir", spy)
    return handles


