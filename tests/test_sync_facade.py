def test_open_session_differs_only_in_the_transport_it_accepts():
    """The one argument that has to change type, isolated so the rest cannot change with it.

    A blocking `open_session` needs the portal the transport is already running on -- that is
    the whole reason `SyncTransport` exists rather than the bare transport being handed back.
    """
    ours = {p.name: p for p in parameters(open_session)}
    theirs = {p.name: p for p in parameters(async_open_session)}
    assert set(ours) == set(theirs)
    assert ours["transport"].annotation == "SyncTransport"
    assert theirs["transport"].annotation == "Transport"
    for name in set(ours) - {"transport"}:
        assert ours[name] == theirs[name], name


